#!/usr/bin/env bash
# Writes .env.local from AWS Secrets Manager (everyops/runtime-db and everyops/auth-config).
# Values are written straight to the file and never printed.
set -euo pipefail
cd "$(dirname "$0")/.."
export AWS_PROFILE="${AWS_PROFILE:-mrjim-new}" AWS_REGION="${AWS_REGION:-ap-southeast-1}"
DB_JSON="$(aws secretsmanager get-secret-value --secret-id everyops/runtime-db --query SecretString --output text)"
AUTH_JSON="$(aws secretsmanager get-secret-value --secret-id everyops/auth-config --query SecretString --output text)"
DB_JSON="$DB_JSON" AUTH_JSON="$AUTH_JSON" APP_URL="${BETTER_AUTH_URL:-http://localhost:3000}" python3 - <<'PY'
import json, os, urllib.parse
db = json.loads(os.environ["DB_JSON"])
auth = json.loads(os.environ["AUTH_JSON"])
url = "postgres://{}:{}@{}:{}/{}".format(
    urllib.parse.quote(db["username"], safe=""), urllib.parse.quote(db["password"], safe=""),
    db["host"], db["port"], db["dbname"])
lines = [
    "# Generated by scripts/pull-env.sh from AWS Secrets Manager. Do not commit.",
    f"DATABASE_URL={url}",
    f"BETTER_AUTH_SECRET={auth['BETTER_AUTH_SECRET']}",
    f"BETTER_AUTH_URL={os.environ['APP_URL']}",
]
with open(".env.local", "w") as f:
    f.write("\n".join(lines) + "\n")
os.chmod(".env.local", 0o600)
print("Wrote .env.local")
PY
